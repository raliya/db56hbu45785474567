if (!function_exists('brand_meta_load_lines_root')) {
    function brand_meta_load_lines_root(string $filename, string $rootDir): array
    {
        $path = rtrim($rootDir, '/\\') . DIRECTORY_SEPARATOR . $filename;

        if (!is_file($path) || !is_readable($path)) {
            return [];
        }

        $lines = file($path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
        if (!is_array($lines)) {
            return [];
        }

        $lines = array_values(array_filter(array_map('trim', $lines), static function ($line) {
            return $line !== '';
        }));

        return $lines;
    }
}

if (!function_exists('brand_meta_fill')) {
    function brand_meta_fill(string $template, array $vars): string
    {
        $replace = [
            '{brand}' => $vars['brand'] ?? '',
            '{brand_latin}' => $vars['brand_latin'] ?? '',
            '{brand_ru}' => $vars['brand_ru'] ?? '',
            '{brand_slug}' => $vars['brand_slug'] ?? '',
            '{year}' => $vars['year'] ?? '',
            '%brand%' => $vars['brand'] ?? '',
            '%brand_latin%' => $vars['brand_latin'] ?? '',
            '%brand_ru%' => $vars['brand_ru'] ?? '',
            '%brand_slug%' => $vars['brand_slug'] ?? '',
            '%year%' => $vars['year'] ?? '',
        ];

        $result = strtr($template, $replace);
        $result = preg_replace('/\s+/u', ' ', trim($result));

        return trim((string)$result);
    }
}

if (!function_exists('brand_meta_same_text')) {
    function brand_meta_same_text(string $a, string $b): bool
    {
        $a = trim($a);
        $b = trim($b);

        if (function_exists('mb_strtolower')) {
            return mb_strtolower($a, 'UTF-8') === mb_strtolower($b, 'UTF-8');
        }

        return strtolower($a) === strtolower($b);
    }
}

if (!function_exists('brand_meta_contains_brand')) {
    function brand_meta_contains_brand(string $text, string $brandLatin, string $brandRu): bool
    {
        $text = trim($text);

        if ($text === '') {
            return false;
        }

        if ($brandLatin !== '') {
            if (function_exists('mb_stripos')) {
                if (mb_stripos($text, $brandLatin, 0, 'UTF-8') !== false) {
                    return true;
                }
            } elseif (stripos($text, $brandLatin) !== false) {
                return true;
            }
        }

        if ($brandRu !== '') {
            if (function_exists('mb_stripos')) {
                if (mb_stripos($text, $brandRu, 0, 'UTF-8') !== false) {
                    return true;
                }
            } elseif (stripos($text, $brandRu) !== false) {
                return true;
            }
        }

        return false;
    }
}

if (!function_exists('brand_meta_build_display')) {
    function brand_meta_build_display(string $brandLatin, string $brandRu): string
    {
        $brandLatin = trim($brandLatin);
        $brandRu = trim($brandRu);

        if ($brandLatin === '' && $brandRu === '') {
            return 'Brand';
        }

        if ($brandLatin !== '' && $brandRu !== '' && !brand_meta_same_text($brandLatin, $brandRu)) {
            return $brandLatin;
        }

        return $brandLatin !== '' ? $brandLatin : $brandRu;
    }
}

if (!function_exists('brand_meta_starts_with_variant')) {
    function brand_meta_starts_with_variant(string $text, array $variants): bool
    {
        $text = trim((string)preg_replace('/^[\s\-\—\–:;,\.]+/u', '', $text));
        if ($text === '') {
            return false;
        }

        foreach ($variants as $variant) {
            $variant = trim((string)$variant);
            if ($variant === '') {
                continue;
            }

            if (function_exists('mb_strlen') && function_exists('mb_substr') && function_exists('mb_strtolower')) {
                $prefix = mb_substr($text, 0, mb_strlen($variant, 'UTF-8'), 'UTF-8');
                if (mb_strtolower($prefix, 'UTF-8') === mb_strtolower($variant, 'UTF-8')) {
                    return true;
                }
            } else {
                if (strncasecmp($text, $variant, strlen($variant)) === 0) {
                    return true;
                }
            }
        }

        return false;
    }
}

if (!function_exists('brand_meta_force_brand_first')) {
    function brand_meta_force_brand_first(string $text, string $brandDisplay, string $brandLatin = '', string $brandRu = ''): string
    {
        $text = trim((string)preg_replace('/\s+/u', ' ', $text));
        if ($text === '') {
            return $brandDisplay;
        }

        if (brand_meta_starts_with_variant($text, [$brandDisplay, $brandLatin, $brandRu])) {
            return $text;
        }

        $text = ltrim($text, " \t\n\r\0\x0B-—–:;,.");
        return trim($brandDisplay . ' — ' . $text);
    }
}

if (!function_exists('brand_meta_cache_file')) {
    function brand_meta_cache_file(string $rootDir, string $slug, string $page): string
    {
        $dir = rtrim($rootDir, '/\\') . '/meta_cache';

        if (!is_dir($dir)) {
            @mkdir($dir, 0775, true);
        }

        $safeSlug = preg_replace('/[^a-zA-Z0-9_-]/', '_', $slug);
        $safePage = preg_replace('/[^a-zA-Z0-9_-]/', '_', $page);

        return $dir . '/' . $safeSlug . '__' . $safePage . '.json';
    }
}

if (!function_exists('brand_meta_cache_load')) {
    function brand_meta_cache_load(string $cacheFile): ?array
    {
        if (!is_file($cacheFile) || !is_readable($cacheFile)) {
            return null;
        }

        $raw = file_get_contents($cacheFile);
        if ($raw === false || $raw === '') {
            return null;
        }

        $data = json_decode($raw, true);
        if (!is_array($data)) {
            return null;
        }

        if (empty($data['title']) || empty($data['description'])) {
            return null;
        }

        return $data;
    }
}

if (!function_exists('brand_meta_cache_save')) {
    function brand_meta_cache_save(string $cacheFile, string $title, string $description): void
    {
        $payload = [
            'title' => $title,
            'description' => $description,
            'created_at' => date('c'),
        ];

        file_put_contents(
            $cacheFile,
            json_encode($payload, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT),
            LOCK_EX
        );
    }
}

if (!function_exists('brand_meta_pick_once')) {
    function brand_meta_pick_once(array $lines, string $fallback): string
    {
        if (!$lines) {
            return $fallback;
        }

        $index = array_rand($lines);
        return trim((string)$lines[$index]);
    }
}

